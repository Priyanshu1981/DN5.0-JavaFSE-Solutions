// Hands-on 6: Define a class named "Trainer" with the required properties.
class Trainer {
  constructor(trainerId, name, email, phone, technology, skills) {
    this.TrainerId = trainerId;
    this.Name = name;
    this.Email = email;
    this.Phone = phone;
    this.Technology = technology;
    this.Skills = skills;
  }
}

export default Trainer;
